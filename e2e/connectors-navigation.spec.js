  await expect(page.getByRole('button', { name: /volver a tonos/i })).toBeVisible();
  await page.goBack();
  await expect(page.getByRole('button', { name: /元音/ })).toBeVisible();
  await page.getByRole('button', { name: /^volver$/i }).click();
  await page.getByRole('button', { name: 'Practicar', exact: true }).click();
  await page.getByRole('button', { name: 'Escuchar', exact: true }).click();
  await expect(page.getByRole('button', { name: /todas las categorías/i })).toBeVisible();
  await page.goBack();
  await expect(page.getByRole('button', { name: 'Escuchar', exact: true })).toBeVisible();
  await page.getByRole('button', { name: /historias interactivas/i }).click();
  await expect(page.getByText('Mapa de historias')).toBeVisible();
  await page.locator('.story-map-card:not([disabled])').first().click();
  await expect(page.getByText('Mapa de historias')).not.toBeVisible();
  await page.goBack();
  await expect(page.getByText('Mapa de historias')).toBeVisible();
  await page.goBack();
