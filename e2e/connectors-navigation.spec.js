  await page.getByRole('button', { name: /introducción radicales/i }).click();
  await page.getByRole('button', { name: /radicales las piezas/i }).click();
  await page.getByRole('button', { name: /teoría aprende/i }).click();
  await expect(page.getByRole('heading', { name: /teoría de radicales/i })).toBeVisible();
  await page.goBack();
  await expect(page.getByRole('button', { name: /quiz de identificación/i })).toBeVisible();
  await page.goForward();
  await expect(page.getByRole('heading', { name: /teoría de radicales/i })).toBeVisible();
  await page.getByRole('button', { name: /volver a radicales/i }).click();
  await expect(page.getByRole('button', { name: /quiz de identificación/i })).toBeVisible();
  await page.getByRole('button', { name: /^volver$/i }).click();
