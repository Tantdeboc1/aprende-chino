  await page.getByRole('button', { name: /clasificadores repasa/i }).click();
  await expect(page.getByRole('searchbox')).toBeVisible();
  await page.getByRole('group').getByRole('button', { name: 'Practicar', exact: true }).click();
  await page.getByRole('button', { name: /practicar 22 formas/i }).click();
  await expect(page.getByText(/pregunta 1 de/i)).toBeVisible();
  await page.goBack();
  await expect(page.getByRole('button', { name: /practicar 22 formas/i })).toBeVisible();
  await page.goBack();
